using System;
using System.Collections.Generic;
using UnityEngine;

namespace SlimeJumping.TerrainShape
{
    [Serializable]
    public class OutlinePoint
    {
        public int id;
        public Vector2 pos;
        public bool smooth;
        public Vector2 tangentOut;
        public Vector2 tangentIn;
    }

    [Serializable]
    public class OutlineLoop
    {
        public List<OutlinePoint> points = new List<OutlinePoint>();
    }

    [Serializable]
    public class OutlineLayer
    {
        public string name = "Layer";
        public float z = 0f;
        public List<OutlineLoop> loops = new List<OutlineLoop>();

        // Pre-v2 single-loop assets stored their outline here. Only MigrateLegacyOutlineIfNeeded
        // may read or write it.
        [Obsolete("Migrated into loops[0] by MigrateLegacyOutlineIfNeeded.")]
        public List<OutlinePoint> outline = null;
    }

    [Serializable]
    public class InteriorPoint
    {
        public int id;
        public Vector3 pos;
        public bool autoGenerated;
        public float zOffset;  // when useHeightmap is on: effectiveZ = sample(x,y) + zOffset
    }

    [Serializable]
    public class ForcedEdge
    {
        public int idA;
        public int idB;
    }

    public enum AutoSubdivideMode
    {
        Grid,
        JitteredGrid,
        PoissonDisk,
        Halton,
        // Adaptive: per-cell most-interior pick. Spacing controls cell size; narrow
        // strips (width < spacing) still receive one centerline point per cell.
        Adaptive,
    }

    [ExecuteAlways]
    [DisallowMultipleComponent]
    [RequireComponent(typeof(MeshFilter))]
    public class TerrainShape2D : MonoBehaviour
    {
        public List<OutlineLayer> layers = new List<OutlineLayer>();
        public List<InteriorPoint> interior = new List<InteriorPoint>();
        public List<ForcedEdge> forcedEdges = new List<ForcedEdge>();

        [Range(2, 128)]
        public int subdivisionsPerSegment = 24;

        // Smooth segments are subdivided this many times more finely than straight ones.
        [Range(1, 16)]
        public int curveSubdivisionMultiplier = 4;

        [Min(0.05f)]
        public float autoSpacing = 0.4f;

        public AutoSubdivideMode autoMode = AutoSubdivideMode.Adaptive;
        public int autoSeed = 1;
        [Range(0, 8)]
        public int autoLloydIters = 0;

        public bool doubleSidedFront = false;

        // Texture tiles per world unit for the generated UVs (box projection).
        [Min(0.001f)]
        public float uvScale = 1f;

        public bool flatShaded = false;

        [Min(0f)]
        public float planarSimplifyThreshold = 0f;

        public Material installMaterial;
        public bool installAutoGenerateCollider2D = false;

        public bool useHeightmap = false;
        public bool showHeightmapInScene = false;
        public byte[] heightmapData;
        public int heightmapW = 128;
        public int heightmapH = 128;
        public float heightmapZMin = -0.5f;
        public float heightmapZMax = 0.5f;

        public bool HasHeightmap => heightmapData != null && heightmapW > 0 && heightmapH > 0
            && heightmapData.Length == heightmapW * heightmapH;

        // bbox of the union of all loops in `layer`. Returns false if the layer has no points.
        public static bool ComputeUnionBounds(OutlineLayer layer, out Vector2 min, out Vector2 max)
        {
            min = max = Vector2.zero;
            if (layer == null || layer.loops == null) return false;
            bool first = true;
            foreach (var loop in layer.loops)
            {
                if (loop == null || loop.points == null) continue;
                foreach (var p in loop.points)
                {
                    if (first) { min = max = p.pos; first = false; }
                    else
                    {
                        min = Vector2.Min(min, p.pos);
                        max = Vector2.Max(max, p.pos);
                    }
                }
            }
            return !first;
        }

        public float SampleHeightmapZ(Vector2 local)
        {
            var L = FrontLayer;
            if (L == null || OutlineCount < 3) return 0f;
            if (!useHeightmap || !HasHeightmap) return L.z;
            if (!ComputeUnionBounds(L, out var mn, out var mx)) return L.z;
            Vector2 size = mx - mn;
            if (size.x < 1e-6f || size.y < 1e-6f) return L.z;

            float u = Mathf.Clamp01((local.x - mn.x) / size.x);
            float v = Mathf.Clamp01((local.y - mn.y) / size.y);
            float fx = u * (heightmapW - 1);
            float fy = v * (heightmapH - 1);
            int x0 = (int)fx, y0 = (int)fy;
            int x1 = Mathf.Min(x0 + 1, heightmapW - 1);
            int y1 = Mathf.Min(y0 + 1, heightmapH - 1);
            float tx = fx - x0, ty = fy - y0;
            float v00 = heightmapData[y0 * heightmapW + x0] / 255f;
            float v10 = heightmapData[y0 * heightmapW + x1] / 255f;
            float v01 = heightmapData[y1 * heightmapW + x0] / 255f;
            float v11 = heightmapData[y1 * heightmapW + x1] / 255f;
            float vbi = Mathf.Lerp(Mathf.Lerp(v00, v10, tx), Mathf.Lerp(v01, v11, tx), ty);
            // Red (paint=1) maps to zMin (smaller Z, closer to camera). Blue (paint=0) maps to zMax (further).
            return Mathf.Lerp(heightmapZMax, heightmapZMin, vbi);
        }

        [SerializeField]
        private int nextId = 1;

        public int AllocateId() => nextId++;

        public OutlineLayer FrontLayer => layers.Count > 0 ? layers[0] : null;
        public OutlineLayer BackLayer => layers.Count > 0 ? layers[layers.Count - 1] : null;

        // Total front-layer points. Valid-outline gate: mesh build needs >= 3 in one loop AND >= 3 total.
        public int OutlineCount
        {
            get
            {
                var L = FrontLayer;
                if (L == null || L.loops == null) return 0;
                int total = 0;
                for (int i = 0; i < L.loops.Count; i++)
                    if (L.loops[i] != null && L.loops[i].points != null) total += L.loops[i].points.Count;
                return total;
            }
        }

        public OutlinePoint FindOutlineByIdInLayer(OutlineLayer layer, int id)
        {
            if (layer == null || layer.loops == null) return null;
            for (int li = 0; li < layer.loops.Count; li++)
            {
                var pts = layer.loops[li].points;
                for (int i = 0; i < pts.Count; i++)
                    if (pts[i].id == id) return pts[i];
            }
            return null;
        }

        // (loopIndex, pointIndex) of the vertex with the given id, if found.
        public bool TryFindOutlineLocByIdInLayer(OutlineLayer layer, int id, out int loopIndex, out int pointIndex)
        {
            loopIndex = -1; pointIndex = -1;
            if (layer == null || layer.loops == null) return false;
            for (int li = 0; li < layer.loops.Count; li++)
            {
                var pts = layer.loops[li].points;
                for (int i = 0; i < pts.Count; i++)
                {
                    if (pts[i].id == id) { loopIndex = li; pointIndex = i; return true; }
                }
            }
            return false;
        }

        public InteriorPoint FindInteriorById(int id)
        {
            for (int i = 0; i < interior.Count; i++)
                if (interior[i].id == id) return interior[i];
            return null;
        }

        public bool TryGetPositionByIdOnFront(int id, out Vector3 pos)
        {
            if (FrontLayer != null)
            {
                var o = FindOutlineByIdInLayer(FrontLayer, id);
                if (o != null) { pos = new Vector3(o.pos.x, o.pos.y, FrontLayer.z); return true; }
            }
            var p = FindInteriorById(id);
            if (p != null) { pos = GetEffectiveInteriorPos(p); return true; }
            pos = default;
            return false;
        }

        public Vector3 GetEffectiveInteriorPos(InteriorPoint ip)
        {
            if (useHeightmap && HasHeightmap)
            {
                float baseZ = SampleHeightmapZ(new Vector2(ip.pos.x, ip.pos.y));
                return new Vector3(ip.pos.x, ip.pos.y, baseZ + ip.zOffset);
            }
            return ip.pos;
        }

        public void AddLayerCopy(int copyFromIndex, float zOffset = 0.5f)
        {
            if (layers.Count == 0) return;
            int srcIdx = Mathf.Clamp(copyFromIndex, 0, layers.Count - 1);
            var src = layers[srcIdx];
            var copy = new OutlineLayer
            {
                name = $"Layer {layers.Count}",
                z = src.z + zOffset,
                loops = new List<OutlineLoop>(src.loops.Count)
            };
            foreach (var loop in src.loops)
            {
                var copyLoop = new OutlineLoop { points = new List<OutlinePoint>(loop.points.Count) };
                foreach (var p in loop.points)
                {
                    copyLoop.points.Add(new OutlinePoint
                    {
                        id = p.id,
                        pos = p.pos,
                        smooth = p.smooth,
                        tangentIn = p.tangentIn,
                        tangentOut = p.tangentOut
                    });
                }
                copy.loops.Add(copyLoop);
            }
            layers.Add(copy);
        }

        public void RemoveLayerAt(int index)
        {
            if (layers.Count <= 1) return;
            if (index < 0 || index >= layers.Count) return;
            layers.RemoveAt(index);
        }

        // v2 invariant: every layer holds the same XY for the same id, so the insert goes into
        // every layer at the same XY (no per-layer interpolation).
        public int InsertOutlinePointInAllLayers(int loopIndex, int afterIdx, Vector2 pos)
        {
            if (layers.Count == 0) return 0;
            // Layers must share loop count + vertex order; validate first or a corrupt asset NREs.
            for (int li = 0; li < layers.Count; li++)
            {
                if (layers[li].loops == null || loopIndex < 0 || loopIndex >= layers[li].loops.Count)
                    return 0;
            }
            int newId = AllocateId();
            int insertAt = afterIdx + 1;
            for (int li = 0; li < layers.Count; li++)
            {
                var loop = layers[li].loops[loopIndex];
                loop.points.Insert(insertAt, new OutlinePoint { id = newId, pos = pos });
            }
            return newId;
        }

        // Removes the point from every layer's same-loop; a loop under 3 points is dropped entirely.
        // Refuses (returns false) if the front layer's TOTAL would fall below 3.
        public bool RemoveOutlinePointInAllLayers(int loopIndex, int pointIdx)
        {
            if (layers.Count == 0) return false;
            if (loopIndex < 0 || loopIndex >= FrontLayer.loops.Count) return false;
            // Validate all layers before mutating, else a corrupt asset NREs mid-loop.
            for (int li = 0; li < layers.Count; li++)
            {
                var L = layers[li];
                if (L.loops == null || loopIndex >= L.loops.Count) return false;
                if (pointIdx >= L.loops[loopIndex].points.Count) return false;
            }
            var loop0 = FrontLayer.loops[loopIndex];
            if (pointIdx < 0 || pointIdx >= loop0.points.Count) return false;

            bool wouldRemoveLoop = (loop0.points.Count - 1) < 3;
            int totalAfter = OutlineCount - 1;
            if (wouldRemoveLoop) totalAfter = OutlineCount - loop0.points.Count;
            if (totalAfter < 3) return false;

            int delId = loop0.points[pointIdx].id;
            for (int li = 0; li < layers.Count; li++)
            {
                var L = layers[li];
                var ll = L.loops[loopIndex];
                ll.points.RemoveAt(pointIdx);
                if (ll.points.Count < 3) L.loops.RemoveAt(loopIndex);
            }
            forcedEdges.RemoveAll(fe => fe.idA == delId || fe.idB == delId);
            return true;
        }

        void Reset()
        {
            layers.Clear();
            interior.Clear();
            forcedEdges.Clear();
            nextId = 1;

            var front = new OutlineLayer { name = "Front", z = 0f };
            var loop = new OutlineLoop();
            loop.points.Add(new OutlinePoint { id = AllocateId(), pos = new Vector2(-1f, -1f) });
            loop.points.Add(new OutlinePoint { id = AllocateId(), pos = new Vector2(1f, -1f) });
            loop.points.Add(new OutlinePoint { id = AllocateId(), pos = new Vector2(1f, 1f) });
            loop.points.Add(new OutlinePoint { id = AllocateId(), pos = new Vector2(-1f, 1f) });
            front.loops.Add(loop);
            layers.Add(front);

            AddLayerCopy(0, 0.5f);
            layers[1].name = "Back";
        }

        // Copies the legacy `outline` field into loops[0] and clears it. Idempotent.
        public void MigrateLegacyOutlineIfNeeded()
        {
            if (layers == null) return;
            for (int li = 0; li < layers.Count; li++)
            {
                var L = layers[li];
                if (L == null) continue;
                if (L.loops == null) L.loops = new List<OutlineLoop>();

#pragma warning disable 0618
                var legacy = L.outline;
                if (legacy != null && legacy.Count > 0 && L.loops.Count == 0)
                {
                    L.loops.Add(new OutlineLoop { points = new List<OutlinePoint>(legacy) });
                }
                L.outline = null;
#pragma warning restore 0618
            }
        }
    }
}
